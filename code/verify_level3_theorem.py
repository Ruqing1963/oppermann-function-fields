"""
verify_level3_theorem.py -- the L-functions of all characters of exact level 3 of G_3 in characteristic 2.

G_3 = (1 + u F_q[u]) / (u^4), q = 2^k; the class of a monic F of degree n is u^n F(1/u) mod u^4.
H_3 = {1 + A u^2 + B u^3} is a subgroup isomorphic to (F_q^2, +), with characters
lambda_{alpha,beta}(A, B) = (-1)^{Tr(alpha A + beta B)}; a character chi of G_3 has exact level 3 iff its
restriction to H_3 has beta != 0.  There are q^2 (q - 1) such characters.

The characters are constructed from the group law only: with an F_2-basis b_1..b_k of F_q and g_i = 1 + b_i u,
G_3 is generated by H_3 and the g_i, and g_i^2 = 1 + b_i^2 u^2 lies in H_3.  A character extending lambda is fixed
by choosing chi(g_i) among the two square roots of lambda(g_i^2); the value on an arbitrary class is obtained by
multiplying out in G_3.  Multiplicativity is then tested on all pairs of classes (q <= 4) or 40 random pairs per character.

For every character the script checks, with f(x) = chi(1 + x u), s0 = alpha / beta:
  (1) the cocycle  f(x) f(y) = f(x+y) (-1)^{Tr(alpha xy + beta(x^2 y + x y^2))}  for all x, y;
  (2) c_2 = q f(s0),  c_2^2 = q^2 (-1)^{Tr(alpha^3/beta^2)},  c_3 = 0   (c_n = sum of chi over monic F of degree n);
  (3) c_1 = f(s0) conj(c_1),  |c_1|^2 = q (1 + sum of f(t) over the roots t in F_q of beta^2 t^3 + alpha^2 t + beta);
  (4) for every such root: Tr(alpha t^2) = 0 and f(t) = +-1; for three roots f(t1) f(t2) f(t3) = +1;
      r = c_1^2 / c_2 is 1 (no root), 0 or 2 (one root), 0 or 4 (three roots);
  (5) both inverse zeros gamma of L(u, chi) = 1 + c_1 u + c_2 u^2 have |gamma|^2 = q and gamma^6 in q^3 {+-1, +-i};
  (6) selection rule: r = 1 only if c_2^2 = +(-1)^k q^2, r = 2 only if c_2^2 = -(-1)^k q^2; the normalised zeros
      gamma / sqrt(q) are 24th roots of unity of order dividing 8 or (k odd) of order 24, (k even) of order 3, 6, 12.

Usage: python verify_level3_theorem.py [k ...]      (default 1 2 3 4; output also in ../data/level3_theorem.txt)
"""
import cmath
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = open(os.path.join(HERE, "..", "data", "level3_theorem.txt"), "w", encoding="utf8")
IRRED = {1: 0b11, 2: 0b111, 3: 0b1011, 4: 0b10011, 5: 0b100101}
I4 = np.array([1, 1j, -1, -1j])


def say(s=""):
    print(s, flush=True)
    OUT.write(s + "\n")
    OUT.flush()


def field(k):
    q = 1 << k
    mod = IRRED[k]

    def mul(a, b):
        r = 0
        while b:
            if b & 1:
                r ^= a
            a <<= 1
            if a & q:
                a ^= mod
            b >>= 1
        return r
    M = np.array([[mul(a, b) for b in range(q)] for a in range(q)], np.int64)
    tr = np.zeros(q, np.int64)
    for x in range(q):
        t, y = 0, x
        for _ in range(k):
            t ^= y
            y = int(M[y, y])
        assert t in (0, 1)
        tr[x] = t
    inv = np.zeros(q, np.int64)
    for a in range(1, q):
        inv[a] = int(np.nonzero(M[a] == 1)[0][0])
    return q, M, tr, inv


def gmul(M, x, y):
    """product in G_3 of classes x = (e1, e2, e3), y = (f1, f2, f3) (1 + e1 u + e2 u^2 + e3 u^3 mod u^4)."""
    e1, e2, e3 = x
    f1, f2, f3 = y
    return (e1 ^ f1, e2 ^ f2 ^ int(M[e1, f1]), e3 ^ f3 ^ int(M[e1, f2]) ^ int(M[e2, f1]))


def run(k, rng):
    q, M, tr, inv = field(k)
    sq = np.array([M[x, x] for x in range(q)])
    # decomposition of every class as (product of g_i^{eps_i}) * h, h in H_3, by multiplying out in G_3
    # classes are indexed by (e1, e2, e3); word[e1] = (A0, B0) with prod_{i in bits(e1)} g_i = (1 + e1 u)(1 + A0 u^2 + B0 u^3)
    word = {}
    for e1 in range(q):
        g = (0, 0, 0)
        for i in range(k):
            if e1 >> i & 1:
                g = gmul(M, g, (1 << i, 0, 0))
        assert g[0] == e1
        # g = (1 + e1 u) * (1 + A u^2 + B u^3)  =>  A = g[1], B = g[2] + e1 * A
        A0 = g[1]
        B0 = g[2] ^ int(M[e1, A0])
        assert gmul(M, (e1, 0, 0), (0, A0, B0)) == g
        word[e1] = (A0, B0)
    xs = np.arange(q)
    X, Y = np.meshgrid(xs, xs, indexing="ij")
    XY = M[X, Y]
    X2Y = M[sq[X], Y] ^ M[X, sq[Y]]
    stats = dict(chars=0, mult=0, cocycle=0, c2=0, c2sq=0, c3=0, c1sym=0, c1abs=0, roots_tr=0, roots_pm=0, prod3=0,
                 r_ok=0, gam_abs=0, gam6=0, sel=0, order=0)
    nthree = 0
    rhist = {}
    occupied = set()
    pairs = None
    for alpha in range(q):
        for beta in range(1, q):
            lam = lambda A, B: (tr[M[alpha, A] ^ M[beta, B]] * 2) % 4          # exponent of i
            s0 = int(M[alpha, inv[beta]])
            a3b2 = int(M[M[alpha, M[alpha, alpha]], inv[M[beta, beta]]])
            roots = [t for t in range(1, q)
                     if M[M[beta, beta], M[t, M[t, t]]] ^ M[M[alpha, alpha], t] ^ beta == 0]
            for choice in range(q):
                # chi(g_i) = i^{e_i}, 2 e_i = exponent of lambda(g_i^2) = lambda(b_i^2, 0)
                gexp = []
                for i in range(k):
                    half = int(lam(int(sq[1 << i]), 0)) // 2                      # 0 or 1
                    gexp.append((half + 2 * (choice >> i & 1)) % 4)
                # f(x) = chi(1 + x u) = prod chi(g_i)^{eps_i} / lambda(word)
                fexp = np.zeros(q, np.int64)
                for e1 in range(q):
                    s = sum(gexp[i] for i in range(k) if e1 >> i & 1)
                    A0, B0 = word[e1]
                    fexp[e1] = (s - int(lam(A0, B0))) % 4

                def chi_exp(e1, e2, e3):                                        # (1 + e1 u)(1 + e2 u^2 + (e3 + e1 e2) u^3)
                    return (fexp[e1] + lam(e2, e3 ^ M[e1, e2])) % 4
                stats["chars"] += 1
                # multiplicativity
                if q <= 4:
                    allc = [(a, b, c) for a in range(q) for b in range(q) for c in range(q)]
                    test = [(x, y) for x in allc for y in allc]
                else:
                    if pairs is None:
                        pairs = rng.integers(0, q, size=(40, 6))
                    test = [(tuple(int(v) for v in p[:3]), tuple(int(v) for v in p[3:])) for p in pairs]
                ok = all((chi_exp(*x) + chi_exp(*y) - chi_exp(*gmul(M, x, y))) % 4 == 0 for x, y in test)
                stats["mult"] += ok
                # (1) cocycle
                lhs = (fexp[X] + fexp[Y] - fexp[X ^ Y]) % 4
                rhs = (2 * tr[M[alpha, XY] ^ M[beta, X2Y]]) % 4
                stats["cocycle"] += bool(np.all(lhs == rhs))
                f = I4[fexp]
                # (2) c_1, c_2, c_3 by direct summation over monic polynomials
                c1 = complex(np.sum(f))
                E1, E2 = np.meshgrid(xs, xs, indexing="ij")
                ex2 = (fexp[E1] + 2 * tr[M[alpha, E2] ^ M[beta, M[E1, E2]]]) % 4      # class (e1, e2, 0)
                c2 = complex(np.sum(I4[ex2]))
                E1, E2, E3 = np.meshgrid(xs, xs, xs, indexing="ij")
                ex3 = (fexp[E1] + 2 * tr[M[alpha, E2] ^ M[beta, E3 ^ M[E1, E2]]]) % 4
                c3 = complex(np.sum(I4[ex3]))
                c1 = complex(round(c1.real), round(c1.imag))
                c2 = complex(round(c2.real), round(c2.imag))
                stats["c2"] += (c2 == q * f[s0])
                stats["c2sq"] += (c2 * c2 == q * q * (-1) ** int(tr[a3b2]))
                stats["c3"] += (abs(c3) < 1e-9)
                # (3)
                stats["c1sym"] += (c1 == f[s0] * c1.conjugate())
                fr = [f[t] for t in roots]
                sfr = complex(sum(fr))
                stats["c1abs"] += (c1.real ** 2 + c1.imag ** 2 == q * (1 + sfr.real) and sfr.imag == 0)
                # (4)
                stats["roots_tr"] += all(tr[M[alpha, sq[t]]] == 0 for t in roots)
                stats["roots_pm"] += all(v in (1, -1) for v in fr)
                if len(roots) == 3:
                    nthree += 1
                    stats["prod3"] += (fr[0] * fr[1] * fr[2] == 1)
                r = c1 * c1 / c2
                rint = int(round(r.real))
                good = abs(r - rint) < 1e-9 and rint in {0: (1,), 1: (0, 2), 3: (0, 4)}[len(roots)]
                stats["r_ok"] += good
                rhist[(len(roots), rint)] = rhist.get((len(roots), rint), 0) + 1
                # (5) inverse zeros: roots of X^2 + c1 X + c2
                disc = cmath.sqrt(c1 * c1 - 4 * c2)
                gams = [(-c1 + disc) / 2, (-c1 - disc) / 2]
                stats["gam_abs"] += all(abs(abs(g) ** 2 - q) < 1e-7 for g in gams)
                g6 = [g ** 6 / q ** 3 for g in gams]
                stats["gam6"] += all(min(abs(v - w) for w in I4) < 1e-7 for v in g6)
                # (6)
                sign = int(round((c2 * c2).real)) // (q * q)
                sel = True
                if rint == 1:
                    sel = sign == (-1) ** k
                if rint == 2:
                    sel = sign == -((-1) ** k)
                stats["sel"] += sel
                okord = True
                for g in gams:
                    z = g / np.sqrt(q)
                    j = int(round(cmath.phase(z) / (2 * np.pi / 24))) % 24
                    okord &= abs(z - cmath.exp(2j * np.pi * j / 24)) < 1e-7
                    order = 24 // np.gcd(j, 24)
                    okord &= (order in (1, 2, 4, 8)) or (order == 24 if k % 2 else order in (3, 6, 12))
                    occupied.add(j)
                stats["order"] += okord
    n = stats["chars"]
    say("=== k = %d, q = %d: %d characters of exact level 3 (q^2 (q-1) = %d) ===" % (k, q, n, q * q * (q - 1)))
    lab = [("mult", "chi is multiplicative on G_3 (%s)" % ("all pairs of classes" if q <= 4 else "40 random pairs per character")),
           ("cocycle", "(1) cocycle of f, all (x, y)"),
           ("c2", "(2) c_2 = q f(alpha/beta)"), ("c2sq", "(2) c_2^2 = q^2 (-1)^Tr(alpha^3/beta^2)"),
           ("c3", "(2) c_3 = 0 (deg L = 2)"),
           ("c1sym", "(3) c_1 = f(s0) conj(c_1)"), ("c1abs", "(3) |c_1|^2 = q (1 + sum over roots f(t))"),
           ("roots_tr", "(4) Tr(alpha t^2) = 0 at every root"), ("roots_pm", "(4) f(t) = +-1 at every root"),
           ("r_ok", "(4) r = 1 | 0,2 | 0,4 for 0 | 1 | 3 roots"),
           ("gam_abs", "(5) |gamma|^2 = q"), ("gam6", "(5) gamma^6 in q^3 {+-1, +-i}"),
           ("sel", "(6) selection rule for r = 1, 2"), ("order", "(6) orders of gamma/sqrt(q)")]
    allok = True
    for key, text in lab:
        say("  %-62s %d / %d" % (text, stats[key], n))
        allok &= stats[key] == n
    say("  %-62s %d / %d" % ("(4) f(t1) f(t2) f(t3) = +1 (characters with three roots)", stats["prod3"], nthree))
    allok &= stats["prod3"] == nthree
    say("  (number of roots, r): " + ", ".join("%s: %d" % (kk, v) for kk, v in sorted(rhist.items())))
    say("  24th roots of unity occupied by gamma/sqrt(q): %d of 24: exponents %s" % (len(occupied), sorted(occupied)))
    say("  ALL CHECKS PASS: %s" % allok)
    return allok


if __name__ == "__main__":
    ks = [int(x) for x in sys.argv[1:]] or [1, 2, 3, 4]
    rng = np.random.default_rng(1)
    res = [run(k, rng) for k in ks]
    say("\nsummary: " + ", ".join("q=%d: %s" % (1 << k, r) for k, r in zip(ks, res)))
